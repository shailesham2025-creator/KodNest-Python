# Arithmetic operators
print(3+3) #6
print(3-3) #0
print(3*3) #9
print(3/3) #1
print(3%3) #0
print(3**3) #27
print(3//3) #1

# Comparison operators
print(3==3) #True
print(3!=3) #False
print(3>3) #False
print(3<3) #False
print(3>=3) #True
print(3<=3) #True

# Logical operators
print(11==10 and 1==1) #False
print(11==10 or 1==1) #True
print(not 1==1) #False

#Bitwise operators
